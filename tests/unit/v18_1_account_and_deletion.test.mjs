import {source as pageSource} from './source.mjs';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read=p=>readFileSync(new URL('../../'+p,import.meta.url),'utf8');
const auth=pageSource('frontend/apply.html');
const css=read('frontend/css/components.css');
const admin=pageSource('frontend/admin-dashboard.html');
const fn=read('supabase/functions/admin-delete/index.ts');
const sql=read('supabase/migrations/029_v18_safe_draft_deletion_and_document_gates.sql');
assert.match(css,/grid-template-columns:minmax\(250px,1fr\) minmax\(0,2fr\)/,'sign-in panel must take at least two-thirds');
assert.match(css,/#auth \.authbox\{width:min\(100%,660px\)/,'form width must not be capped at 440px');
assert.match(css,/#menu button\[role=menuitem\]/,'settings labels need explicit contrast overrides');
assert.match(css,/@media \(max-width: 480px\)/,'phone layout required');
assert.match(auth,/function signOut\(\)/,'sign out handler required');
const logout=auth.slice(auth.indexOf('function signOut(){'),auth.indexOf('function showAuth(){'));
assert.ok(logout.indexOf("$('#app').hidden=true")<logout.indexOf("sb.auth.signOut"),'UI must change before delayed SDK logout');
assert.ok(!logout.includes('location.replace('),'no same-page hash-only navigation for sign-out');
assert.match(logout,/signOut\(\{scope:'local'\}\)/,'Supabase session must be ended locally');
assert.match(admin,/data-perm-del=/,'direct applications-list permanent delete button required');
assert.match(admin,/delDialog\('application',b\.dataset\.permDel\)/,'row action must open protected deletion dialog');
assert.match(admin,/m\.querySelector\('#dc'\)/,'typed confirmation required');
assert.match(admin,/m\.querySelector\('#dr'\)/,'reason required');
assert.match(fn,/\.rpc\("admin_delete_nonadmitted"/,'server must execute gated transactional RPC');
assert.match(sql,/where id=p_application for update/i,'database deletion must lock record');
assert.match(sql,/exists\(select 1 from public\.payments/i,'financial dependency protection required');
assert.match(sql,/insert into public\.audit_log/i,'deletion audited');
console.log('V18.1 UI, sign-out, protected permanent deletion checks: PASS');
