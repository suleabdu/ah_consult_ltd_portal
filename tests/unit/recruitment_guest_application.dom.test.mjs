import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';

const html=readFileSync('frontend/recruitment.html','utf8');
const script=readFileSync('frontend/js/recruitment.js','utf8');
const vacancy='11111111-1111-4111-8111-111111111111';
const question='22222222-2222-4222-8222-222222222222';
const fileQuestion='33333333-3333-4333-8333-333333333333';
const dom=new JSDOM(html,{url:'https://example.test/recruitment.html',runScripts:'outside-only'});
const w=dom.window,calls=[];
w.HTMLElement.prototype.scrollIntoView=function(){};
w.APPLY_CONFIG={SUPABASE_URL:'https://example.supabase.co',SUPABASE_ANON_KEY:'public'};
w.supabase={createClient:()=>({rpc:async(name)=>name==='recruitment_public_vacancies'?{data:[{id:vacancy,title:'Architect',summary:'Design'}],error:null}:{data:{id:vacancy,title:'Architect',description:'Our role',requires_cv:true,questions:[{id:question,prompt:'Your experience',kind:'text',required:true},{id:fileQuestion,prompt:'Portfolio',kind:'file',required:true}]},error:null},functions:{invoke:async(name,args)=>{calls.push([name,args]);return calls.length===1?{error:{context:{json:async()=>({error:'Please try again later.'})}}}:{data:{id:'success'},error:null}}}})};
w.eval(script);
await new Promise(r=>setTimeout(r,30));
assert.equal(w.document.getElementById('career-count').textContent,'1');
const title=w.document.querySelector('.vacancy-card h3 a');
assert.ok(title.href.includes('job='+vacancy));
const apply=w.document.querySelector('.vacancy-actions .btn-primary');
assert.match(apply.textContent,/Apply for this role/);
title.click();await new Promise(r=>setTimeout(r,20));
assert.equal(w.document.querySelector('#detail-content h2').textContent,'Architect');
w.document.getElementById('careerBack').click();assert.equal(w.document.getElementById('vacancy-detail').hidden,true);
apply.click();await new Promise(r=>setTimeout(r,20));
assert.match(w.document.getElementById('apply-area').textContent,/No account is required/);
const form=w.document.getElementById('careerApplication');
assert.ok(form);
form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
await new Promise(r=>setTimeout(r,10));assert.equal(calls.length,0,'required fields prevent submission');
form.elements.full_name.value='Amina Ade';form.elements.email.value='amina@example.org';form.elements.phone.value='08012345678';
form.querySelector(`[data-question="${question}"]`).value='Five years';form.elements.consent.checked=true;
const pdf=new w.File(['test'],'document.pdf',{type:'application/pdf'});
Object.defineProperty(form.elements.cv,'files',{value:[pdf]});
Object.defineProperty(form.querySelector(`[data-question="${fileQuestion}"]`),'files',{value:[pdf]});
form.reportValidity=()=>true; // jsdom does not update file-input validity from a mocked FileList.
form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
await new Promise(r=>setTimeout(r,20));
assert.equal(calls.length,1);assert.equal(calls[0][0],'recruitment-apply');
const body=JSON.parse(calls[0][1].body.get('payload'));
assert.equal(body.vacancy_id,vacancy);assert.equal(body.answers[question],'Five years');assert.equal(body.consent,true);
assert.match(body.submission_id,/^[0-9a-f-]{36}$/);
assert.equal(calls[0][1].body.get('cv').name,'document.pdf');
assert.equal(calls[0][1].body.get('question:'+fileQuestion).name,'document.pdf');
assert.match(w.document.getElementById('applicationMessage').textContent,/Please try again later/);
assert.equal(form.querySelector('[type=submit]').disabled,false);
form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));await new Promise(r=>setTimeout(r,20));
assert.equal(JSON.parse(calls[1][1].body.get('payload')).submission_id,body.submission_id,'retry preserves submission ID');
assert.match(w.document.getElementById('apply-area').textContent,/Application submitted/);
dom.window.close();
console.log('PASS guest vacancy browsing, application form and direct submission');
